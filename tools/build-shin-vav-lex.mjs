// 1.0.87: builds site/js/shin-vav-lex.js – speech-only spellings for vocalised words whose source lost a shin/sin dot
// or the holam/dagesh of a vav (mostly the Siddur source: שֶׁעָשיתָ, הַנְּשוּאִים, לְעולָם, אולָּם, בָּרוךְ).
// The correct spelling is taken only from the app's own vocalised texts (Tanakh, Siddur, Tanya, Hayom Yom, Rashi, Rambam …):
// the same letters and vowels with the dots/vav marks present. Ambiguous matches (< 80 % agreement) are left out.
import fs from 'node:fs';
import { letters, fixShinVav, shinVavKey, FULLV, SHVA, DAGESH } from '../site/js/g2p.js';
import { speechStrings } from './shin-vav-audit.mjs';

const OUT = new URL('../site/js/shin-vav-lex.js', import.meta.url).pathname;
const tokens = t => t.replace(/<[^>]+>/g, ' ').split(/[\s\u05BE]+/).filter(x => !/[\u05F3\u05F4'"]/.test(x))
  .map(x => x.replace(/[^\u05D0-\u05EA\u05B0-\u05C7]/g, '')).filter(x => /[\u05B0-\u05BB\u05C7]/.test(x));
const full = l => !!l && [...l.diac].some(c => FULLV.has(c));
/** problems that SHIN_VAV_LEX may repair */
export function defects(w) {
  const L = letters(w); let n = 0;
  L.forEach((l, i) => {
    if (l.ch === 'ש' && !/[\u05C1\u05C2]/.test(l.diac) && !(L[i - 1]?.ch === 'ש' && L[i - 1].diac.includes('\u05C2'))) n++;
    const prev = L[i - 1], nxt = L[i + 1];
    if (l.ch === 'ו' && !l.diac && i > 0 && nxt && !full(prev) && !prev.diac.includes(SHVA) && !prev.diac.includes(DAGESH) && /[\u05B0-\u05BB\u05C7]/.test(nxt.diac) && nxt.ch !== 'ו') n++;
  });
  return n;
}
// loose keys: 1 = without shin/sin dots and without the marks of a non-initial vav; 2 = also without any mark on ש
const loose = (w, level) => letters(w).map((l, i) => l.ch + (l.ch === 'ש' ? (level === 2 ? '' : l.diac.replace(/[\u05C1\u05C2]/g, '')) : l.ch === 'ו' && i > 0 ? '' : l.diac)).join('');
const good = [new Map(), new Map()], bad = new Map();
for (const { text } of speechStrings()) for (const raw of tokens(text)) {
  const w = fixShinVav(raw, {}), k = shinVavKey(w);
  if (defects(w)) { bad.set(k, (bad.get(k) || 0) + 1); continue; }
  for (const lv of [1, 2]) { const m = good[lv - 1], key = loose(k, lv); (m.get(key) || m.set(key, new Map()).get(key)).set(k, ((m.get(key).get(k)) || 0) + 1); }
}
// Reviewed by hand for words with no unambiguous vocalised twin in the app's texts (the rest default to shin / holam male).
const MANUAL = { 'אולָּם': 'אוּלָּם', 'וְאולָּם': 'וְאוּלָּם', 'הַיְּהודִּים': 'הַיְּהוּדִּים', 'הַיְהודִּים': 'הַיְהוּדִּים', 'יְהודִּי': 'יְהוּדִּי',
  'הַנְּשוּאִים': 'הַנְּשׂוּאִים', 'וְשחְתָּ': 'וְשַׂחְתָּ' };
const lex = {}, unresolved = [];
for (const [k, v] of Object.entries(MANUAL)) lex[shinVavKey(k)] = v;
for (const [k, n] of [...bad].sort()) {
  if (lex[k]) continue;
  let pick = null;
  for (const lv of [1, 2]) {
    const c = good[lv - 1].get(loose(k, lv)); if (!c) continue;
    const tot = [...c.values()].reduce((a, b) => a + b, 0), [best, bn] = [...c].sort((a, b) => b[1] - a[1])[0];
    if (bn / tot >= 0.8 && letters(best).length === letters(k).length) { pick = best; break; }
  }
  if (pick) lex[k] = pick; else unresolved.push([k, n]);
}
const SRC = '// Generated by tools/build-shin-vav-lex.mjs (1.0.87) – do not edit. Speech only: key = a vocalised word as written in the\n' +
  '// source (letters + sorted niqqud), value = the same letters with the shin/sin dot or vav mark found in the app\'s other vocalised texts.\n' +
  'export const SHIN_VAV_LEX = ' + JSON.stringify(lex, null, 0).replace(/","/g, '",\n"') + ';\n';
// --check: exit 1 if site/js/shin-vav-lex.js is not what this build produces (used by the tests)
if (process.argv.includes('--check')) { const ok = fs.readFileSync(OUT, 'utf8') === SRC; console.log(JSON.stringify({ inSync: ok })); process.exit(ok ? 0 : 1); }
fs.writeFileSync(OUT, SRC);
console.log(JSON.stringify({ defectiveDistinct: bad.size, resolved: Object.keys(lex).length, unresolved: unresolved.length }));
console.log('unresolved:', unresolved.sort((a, b) => b[1] - a[1]).slice(0, 40).map(x => x.join('×')).join(' '));
